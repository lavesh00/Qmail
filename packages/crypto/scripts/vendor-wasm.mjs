/**
 * Copies the two liboqs WASM builds Qmail uses out of node_modules and into
 * `wasm/`, where the package can import them statically.
 *
 * Why this exists, rather than just importing `@oqs/liboqs-js`:
 *
 *   - The package's own loader picks its WASM build with `import(modulePath)`,
 *     a dynamic import whose argument is a variable. Metro rejects that
 *     outright, and bundlers that tolerate it do so by pulling in every file in
 *     `dist/` — all 194 algorithm builds, roughly 15 MB, to use two of them.
 *   - The individual algorithm builds are not reachable through the package's
 *     `exports` map, so a deep import works in a bundler and fails in Node.
 *
 * Copying the two files we actually need sidesteps both problems and leaves
 * every consumer with an ordinary static import. The WASM itself is untouched:
 * this is the same compiled liboqs, byte for byte.
 *
 * Runs automatically before `npm run build`.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

// The package's `exports` map deliberately hides package.json and dist/, so
// resolve the one entry point it does publish and walk up from there. This
// follows npm's hoisting rather than assuming a node_modules layout.
const entry = fileURLToPath(import.meta.resolve('@oqs/liboqs-js'));
const liboqsRoot = join(dirname(entry), '..'); // <root>/src/index.js -> <root>
const { version } = JSON.parse(readFileSync(join(liboqsRoot, 'package.json'), 'utf8'));

/**
 * Emscripten output has no type information, so a declaration file is written
 * beside each build. Kept self-contained rather than importing shared types,
 * because these live outside the compiler's rootDir.
 */
const SHARED_MEMBERS = `  _OQS_init(): void;
  _malloc(size: number): number;
  _free(ptr: number): void;
  lengthBytesUTF8(text: string): number;
  stringToUTF8(text: string, ptr: number, maxBytes: number): number;
  getValue(ptr: number, type: string): number;
  setValue(ptr: number, value: number, type: string): void;
  HEAPU8: Uint8Array;`;

const BUILDS = [
  {
    file: 'ml-kem-768.min.js',
    declaration: `export interface LibOqsKemModule {
${SHARED_MEMBERS}
  _OQS_KEM_new(namePtr: number): number;
  _OQS_KEM_free(kem: number): void;
  _OQS_KEM_keypair(kem: number, publicKey: number, secretKey: number): number;
  _OQS_KEM_encaps(kem: number, ciphertext: number, sharedSecret: number, publicKey: number): number;
  _OQS_KEM_decaps(kem: number, sharedSecret: number, ciphertext: number, secretKey: number): number;
}

declare const factory: (overrides?: Record<string, unknown>) => Promise<LibOqsKemModule>;
export default factory;
`,
  },
  {
    file: 'ml-dsa-65.min.js',
    declaration: `export interface LibOqsSigModule {
${SHARED_MEMBERS}
  _OQS_SIG_new(namePtr: number): number;
  _OQS_SIG_free(sig: number): void;
  _OQS_SIG_keypair(sig: number, publicKey: number, secretKey: number): number;
  _OQS_SIG_sign(sig: number, signature: number, signatureLen: number, message: number, messageLen: number, secretKey: number): number;
  _OQS_SIG_verify(sig: number, message: number, messageLen: number, signature: number, signatureLen: number, publicKey: number): number;
}

declare const factory: (overrides?: Record<string, unknown>) => Promise<LibOqsSigModule>;
export default factory;
`,
  },
];

const outDir = join(packageRoot, 'wasm');
mkdirSync(outDir, { recursive: true });

for (const { file, declaration } of BUILDS) {
  copyFileSync(join(liboqsRoot, 'dist', file), join(outDir, file));
  writeFileSync(
    join(outDir, file.replace(/\.js$/, '.d.ts')),
    `// Generated by scripts/vendor-wasm.mjs — do not edit.\n${declaration}`,
  );
}

// Record which upstream release these came from, so a version bump that changes
// the WASM is visible rather than silent.
writeFileSync(
  join(outDir, 'VERSION'),
  `@oqs/liboqs-js@${version}\n${BUILDS.map((b) => `dist/${b}`).join('\n')}\n`,
);

console.log(`Vendored ${BUILDS.length} liboqs WASM builds from @oqs/liboqs-js@${version}`);
