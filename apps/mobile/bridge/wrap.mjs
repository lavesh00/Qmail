/**
 * Wraps the built crypto host into a TypeScript module exporting one HTML
 * string, which React Native hands straight to the WebView.
 *
 * Inline rather than a bundled asset file on purpose: an inline document has an
 * opaque origin and no way to load anything else, so the crypto host cannot
 * reach the network even if something in it tried to.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const script = readFileSync(join(here, 'build', 'host.js'), 'utf8');

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' 'unsafe-eval'; connect-src 'none'">
</head>
<body>
<script>
${script}
</script>
</body>
</html>`;

// The HTML goes into a template literal, so backslashes, backticks and `${`
// have to be neutralised or the generated module will not parse.
const escaped = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const outDir = join(here, '..', 'lib');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'crypto-host.generated.ts'),
  `/* eslint-disable */
/**
 * Generated by bridge/wrap.mjs — do not edit.
 *
 * The Qmail crypto module, bundled for a WebView. Rebuild with:
 *   npm run build:bridge --workspace @qmail/mobile
 */
export const CRYPTO_HOST_HTML = \`${escaped}\`;
`,
);

console.log(
  `Wrote lib/crypto-host.generated.ts (${(html.length / 1024).toFixed(0)} KB of inline HTML)`,
);
